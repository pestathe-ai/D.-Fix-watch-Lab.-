import '../logic/beat_analyzer.dart';

enum WindType { automatic, manual }

class Caliber {
  final String id;
  final String name;
  final WindType type;
  final int? bph; // null = sconosciuta
  final int? jewels;
  final String? reserve;
  final double? diameterMm;
  final bool hasDate;
  final String? alsoKnownAs;
  final List<String> notes; // note specifiche di questo calibro
  final bool generic;
  /// Scritte incise che lo identificano (normalizzate: maiuscole, senza spazi e trattini).
  final List<String> engravings;
  final bool chrono;

  const Caliber({
    required this.id,
    required this.name,
    required this.type,
    this.bph,
    this.jewels,
    this.reserve,
    this.diameterMm,
    this.hasDate = true,
    this.alsoKnownAs,
    this.notes = const [],
    this.generic = false,
    this.engravings = const [],
    this.chrono = false,
  });

  /// Calibro creato al volo per un movimento che non è in archivio (segue la sequenza universale).
  bool get custom => id.startsWith('custom');

  Map<String, dynamic> toJson() => {
        'id': id,
        'name': name,
        'automatic': type == WindType.automatic,
        if (bph != null) 'bph': bph,
        if (jewels != null) 'jewels': jewels,
        if (reserve != null) 'reserve': reserve,
        'hasDate': hasDate,
        'notes': notes,
        'chrono': chrono,
      };

  factory Caliber.fromJson(Map<String, dynamic> j) => Caliber(
        id: (j['id'] as String?) ?? 'custom',
        name: (j['name'] as String?) ?? 'Movimento',
        type: j['automatic'] == false ? WindType.manual : WindType.automatic,
        bph: (j['bph'] as num?)?.toInt(),
        jewels: (j['jewels'] as num?)?.toInt(),
        reserve: j['reserve'] as String?,
        hasDate: (j['hasDate'] as bool?) ?? true,
        notes: ((j['notes'] as List?) ?? const []).map((e) => e.toString()).toList(),
        generic: true,
        chrono: (j['chrono'] as bool?) ?? false,
      );

  /// Movimento non in archivio: tengo il nome che hai letto (o che ha detto l'AI) e uso la sequenza universale.
  static Caliber unknown({
    required String name,
    required bool automatic,
    int? bph,
    int? jewels,
    bool hasDate = true,
    bool chrono = false,
    List<String> notes = const [],
  }) =>
      Caliber(
        id: 'custom',
        name: name,
        type: automatic ? WindType.automatic : WindType.manual,
        bph: bph,
        jewels: jewels,
        hasDate: hasDate,
        generic: true,
        chrono: chrono,
        notes: [
          ...notes,
          'Non è nel mio archivio: seguo la sequenza universale, che va bene per quasi tutti i movimenti meccanici. '
              'Fotografa ogni passo prima di smontare: le viti le segno io sulla tua foto.',
          if (chrono) 'È un CRONOGRAFO: la guida copre la base ma non il meccanismo del cronografo.',
        ],
      );

  String get typeLabel => type == WindType.automatic ? 'Automatico' : 'Carica manuale';

  String get summary {
    final bits = <String>[typeLabel];
    if (bph != null) bits.add('${_fmt(bph!)} alt/h');
    if (jewels != null) bits.add('$jewels rubini');
    if (reserve != null) bits.add('riserva $reserve');
    return bits.join(' · ');
  }
}

String _fmt(int n) {
  final s = n.toString();
  final b = StringBuffer();
  for (var i = 0; i < s.length; i++) {
    if (i > 0 && (s.length - i) % 3 == 0) b.write('.');
    b.write(s[i]);
  }
  return b.toString();
}

String formatBph(int bph) => _fmt(bph);

